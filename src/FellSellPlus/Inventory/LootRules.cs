using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using MelonLoader.Utils;
using UnityEngine;
using UnityEngine.Localization.Settings;

namespace FellSellPlus.Inventory;

internal enum RuleKind { Default, Never, Always, Total, ThisRun, Need }

internal sealed class ItemRule
{
    [JsonConverter(typeof(JsonStringEnumConverter))]
    public RuleKind Rule { get; set; } = RuleKind.Default;
    public int Limit { get; set; }
    // false: pressing E on a filtered item does nothing (shows "Filtered").
    public bool Manual { get; set; } = true;
    public bool Alert { get; set; } = true;
    public string Note { get; set; }
}

internal sealed class RulesFile
{
    public string Help { get; set; }
    public Dictionary<string, ItemRule> Rules { get; set; } = new();
}

// Rules are edited outside the game; the file is re-read whenever its timestamp changes.
internal static class LootRules
{
    public static string Dir => Path.Combine(MelonEnvironment.UserDataDirectory, "FellSellPlus");
    static string RulesPath => Path.Combine(Dir, "loot_rules.json");
    static string CataloguePath => Path.Combine(Dir, "items_catalogue.txt");

    static readonly JsonSerializerOptions Json = new()
    {
        WriteIndented = true,
        ReadCommentHandling = JsonCommentHandling.Skip,
        AllowTrailingCommas = true,
        PropertyNameCaseInsensitive = true,
    };

    static Dictionary<string, ItemRule> _rules = new(StringComparer.OrdinalIgnoreCase);
    static DateTime _stamp;
    static float _nextCheck;

    public static ItemRule Get(string id) =>
        id != null && _rules.TryGetValue(id, out var r) ? r : null;

    public static void Tick()
    {
        if (Time.unscaledTime < _nextCheck) return;
        _nextCheck = Time.unscaledTime + 3f;
        try
        {
            Directory.CreateDirectory(Dir);
            if (!File.Exists(RulesPath)) WriteDefault();
            var stamp = File.GetLastWriteTimeUtc(RulesPath);
            if (stamp == _stamp) return;
            _stamp = stamp;
            var file = JsonSerializer.Deserialize<RulesFile>(File.ReadAllText(RulesPath), Json);
            _rules = new Dictionary<string, ItemRule>(file?.Rules ?? new(), StringComparer.OrdinalIgnoreCase);
            Plugin.L.LogInfo($"Loot rules loaded: {_rules.Count}.");
        }
        catch (Exception e) { Plugin.L.LogError($"loot_rules.json not loaded (keeping previous rules): {e.Message}"); }
    }

    static void WriteDefault()
    {
        var f = new RulesFile
        {
            Help = "Key = item id from items_catalogue.txt. Rule: Default (game Loot options), Never, Always, " +
                   "Total (pick up while carried+chests+placed < Limit), ThisRun (pick up while picked this run < Limit), " +
                   "Need (pick up while Needed recipes still miss it). Manual=false makes E skip filtered items too. " +
                   "Only items lying loose in the dungeon/forest are affected. Saved changes apply within 3 seconds.",
            Rules = new()
            {
                ["Example_Item_Id"] = new ItemRule { Rule = RuleKind.Never, Note = "replace with a real id, e.g. from items_catalogue.txt" },
            },
        };
        File.WriteAllText(RulesPath, JsonSerializer.Serialize(f, Json));
    }

    static bool _catalogueWritten;

    // One line per item: id, group, rarity, weight, English and Russian name.
    public static void WriteCatalogue()
    {
        if (_catalogueWritten || !InventorySettings.WriteCatalogue.Value || InventoryManager.Instance == null) return;
        _catalogueWritten = true;
        try
        {
            ItemDatabaseUtility.RefreshCache();
            var items = ItemDatabaseUtility._database?.allItems;
            if (items == null || items.Count == 0) { Plugin.L.LogWarning("Item catalogue: database not available."); return; }
            var en = Locale("en"); var ru = Locale("ru");
            var sb = new StringBuilder();
            sb.AppendLine("# Fell & Sell item catalogue, generated by Fell & Sell Plus. Use the first column as the key in loot_rules.json.");
            sb.AppendLine("# id\tgroup\trarity\tweight\tenglish\trussian");
            var seen = new HashSet<string>();
            foreach (var it in items)
            {
                if (it == null || !seen.Add(it.name)) continue;
                string group;
                try { group = AutoPickupRule.Classify(it, false).ToString(); } catch { group = it.itemType.ToString(); }
                sb.Append(it.name).Append('\t').Append(group).Append('\t').Append(it.rarity).Append('\t')
                  .Append(it.weight.ToString("0.##")).Append('\t')
                  .Append(Name(it, en)).Append('\t').Append(Name(it, ru)).AppendLine();
            }
            Directory.CreateDirectory(Dir);
            File.WriteAllText(CataloguePath, sb.ToString());
            Plugin.L.LogInfo($"Item catalogue written: {seen.Count} items -> {CataloguePath}");
        }
        catch (Exception e) { Plugin.L.LogError($"Item catalogue failed: {e.Message}"); }
    }

    static UnityEngine.Localization.Locale Locale(string code)
    {
        try { return LocalizationSettings.AvailableLocales.GetLocale(code); } catch { return null; }
    }

    static string Name(ItemData it, UnityEngine.Localization.Locale loc)
    {
        try
        {
            if (loc != null && it.localizedName != null)
            {
                var s = LocalizationSettings.StringDatabase.GetLocalizedString(
                    it.localizedName.TableReference, it.localizedName.TableEntryReference, loc);
                if (!string.IsNullOrEmpty(s)) return s;
            }
        }
        catch { }
        try { return it.GetDisplayName(); } catch { return it.name; }
    }
}

// Need rule math. The Need list itself (need.json, N key at the bench) belongs to the crafting module.
internal static class NeedList
{
    static List<RecipeData> _recipes;

    // How many more of this item the Needed recipes still use (one craft each), after carried + chests.
    public static int Missing(string itemId)
    {
        _recipes ??= new List<RecipeData>(Resources.FindObjectsOfTypeAll<RecipeData>());
        int need = 0;
        foreach (var r in _recipes)
        {
            if (r == null || r.ingredients == null || !Crafting.NeedList.Has(r)) continue;
            foreach (var ing in r.ingredients)
                if (ing.item != null && ing.item.name == itemId) need += ing.quantity;
        }
        return Math.Max(0, need - ItemCounts.Carried(itemId) - ItemCounts.Stored(itemId));
    }
}
